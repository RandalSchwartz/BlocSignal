import 'string_escape.dart';

/// Validates that [rawUrl] is a non-empty [String] representing a valid HTTPS
/// URL with a non-empty host.
///
/// Trims surrounding whitespace before validation. Throws a [FormatException]
/// if [rawUrl] is `null`, not a [String], empty, whitespace-only, malformed, or
/// uses a scheme other than `https`.
String validateHttpsUrl(dynamic rawUrl) {
  if (rawUrl == null || rawUrl is! String) {
    throw const FormatException('URL must be a non-null String.');
  }
  final trimmed = rawUrl.trim();
  if (trimmed.isEmpty) {
    throw const FormatException('URL cannot be empty.');
  }
  final uri = Uri.tryParse(trimmed);
  if (uri == null ||
      !uri.hasScheme ||
      uri.scheme.toLowerCase() != 'https' ||
      uri.host.trim().isEmpty) {
    throw FormatException('Invalid or non-HTTPS URL: $rawUrl');
  }
  return trimmed;
}

/// Formats a list of [tags] as a `const` Dart `List` literal, escaping each
/// tag for safe embedding in single-quoted string literals.
///
/// Returns `'const []'` if [tags] is `null` or empty.
String formatTagsCode(List<dynamic>? tags) {
  if (tags == null || tags.isEmpty) {
    return 'const []';
  }
  final formattedElements = tags
      .map((t) {
        final str = t?.toString() ?? '';
        return "'${escapeDartString(str)}'";
      })
      .join(', ');
  return 'const [$formattedElements]';
}

/// Extracts a short `'Mon D'` publish date string from a DEV.to [article] map.
///
/// Uses `readable_publish_date` when non-empty, falling back to parsing
/// `published_at` or `created_at`, or `'Aug 8'` if unavailable.
String extractPublishDate(Map<String, dynamic> article) {
  final readable = article['readable_publish_date']?.toString() ?? '';
  if (readable.isNotEmpty && readable != 'null') {
    return readable;
  }
  final rawDate = article['published_at'] ?? article['created_at'];
  if (rawDate != null) {
    final dt = DateTime.tryParse(rawDate.toString());
    if (dt != null) {
      const months = [
        'Jan',
        'Feb',
        'Mar',
        'Apr',
        'May',
        'Jun',
        'Jul',
        'Aug',
        'Sep',
        'Oct',
        'Nov',
        'Dec',
      ];
      return '${months[dt.month - 1]} ${dt.day}';
    }
  }
  return 'Aug 8';
}

/// Derives a display category from an article's [title] and [tags].
String categorizeArticle({required String title, required List<String> tags}) {
  final lowerTitle = title.toLowerCase();
  if (tags.contains('jaspr') ||
      lowerTitle.contains('flutter') ||
      lowerTitle.contains('form')) {
    return 'Flutter & Jaspr';
  }
  if (lowerTitle.contains('bloc') ||
      lowerTitle.contains('state') ||
      lowerTitle.contains('fsm') ||
      lowerTitle.contains('cubit')) {
    return 'State Machines';
  }
  if (tags.contains('opentelemetry') ||
      lowerTitle.contains('observability') ||
      lowerTitle.contains('async')) {
    return 'Interop & Telemetry';
  }
  return 'Architecture';
}

/// Generates the Dart source code representation of a `PublicationItem(...)`
/// instance with all fields escaped against code injection and string
/// interpolation.
///
/// Throws a [FormatException] if [url] is not a valid HTTPS URL.
String generatePublicationItemCode({
  required String title,
  required String description,
  required dynamic url,
  required String date,
  required String readTime,
  required String category,
  String type = 'Article',
  List<dynamic>? tags,
  String indent = '  ',
}) {
  final validatedUrl = validateHttpsUrl(url);
  final escapedTitle = escapeDartString(title);
  final escapedDescription = escapeDartString(description);
  final escapedUrl = escapeDartString(validatedUrl);
  final escapedDate = escapeDartString(date);
  final escapedReadTime = escapeDartString(readTime);
  final escapedCategory = escapeDartString(category);
  final escapedType = escapeDartString(type);
  final formattedTags = formatTagsCode(tags);

  final buffer = StringBuffer()
    ..writeln('${indent}PublicationItem(')
    ..writeln("$indent  title: '$escapedTitle',")
    ..writeln("$indent  description: '$escapedDescription',")
    ..writeln("$indent  url: '$escapedUrl',")
    ..writeln("$indent  date: '$escapedDate',")
    ..writeln("$indent  readTime: '$escapedReadTime',")
    ..writeln("$indent  category: '$escapedCategory',")
    ..writeln("$indent  type: '$escapedType',")
    ..writeln('$indent  tags: $formattedTags,')
    ..write('$indent),');
  return buffer.toString();
}

/// Generates the full contents of `publications_data.g.dart` from a list of
/// decoded DEV.to [articles] maps.
String generatePublicationsDataFile(List<Map<String, dynamic>> articles) {
  final buffer = StringBuffer()
    ..writeln('// GENERATED CODE - DO NOT MODIFY BY HAND')
    ..writeln('// Generated by tool/update_publications.dart')
    ..writeln()
    ..writeln("import '../models/publication_item.dart';")
    ..writeln()
    ..writeln('/// All published DEV.to articles displayed on the website.')
    ..writeln('const List<PublicationItem> publications = [');

  for (final article in articles) {
    final rawTitle = article['title'] as String;
    final description = article['description'] as String;
    final url = article['canonical_url'] ?? article['url'];
    final readTime = '${article['reading_time_minutes']} min read';
    final publishDate = extractPublishDate(article);
    final rawTags = article['tag_list'] as List<dynamic>? ?? const <dynamic>[];
    final tagList = rawTags.map((t) => t.toString()).toList();
    final category = categorizeArticle(title: rawTitle, tags: tagList);

    buffer.writeln(
      generatePublicationItemCode(
        title: rawTitle,
        description: description,
        url: url,
        date: publishDate,
        readTime: readTime,
        category: category,
        type: 'Article',
        tags: tagList,
      ),
    );
  }

  buffer.writeln('];');
  return buffer.toString();
}
